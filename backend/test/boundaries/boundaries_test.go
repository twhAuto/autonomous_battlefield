// Checks which internal packages each backend binary links: forbidden dependencies fail
// the build, and the generated component map must stay current.

package boundaries

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite docs/developer/component-map.md")

const (
	moduleRoot = "../.."
	mapPath    = "../../../docs/developer/component-map.md"
	mapStart   = "<!-- component-map:start (generated by go test ./test/boundaries -update) -->"
	mapEnd     = "<!-- component-map:end -->"
)

// binaries lists the commands in map column order with their display names.
var binaries = []struct{ dir, name string }{
	{"cmd/server", "API"},
	{"cmd/engine", "Engine"},
	{"cmd/aigateway", "AI gateway"},
	{"cmd/agent", "Agent"},
	{"cmd/aieval", "AI eval"},
}

// forbidden maps a package to internal packages it must not depend on, directly or
// transitively. A trailing "/..." also forbids every subpackage.
var forbidden = map[string][]string{
	// The agent is outbound-only: no database, battle state, or gateway signing code.
	"cmd/agent": {"internal/postgres", "internal/battle/...", "internal/faction/repo", "internal/generation/repo", "internal/admin", "internal/members", "internal/app", "internal/ai/mcpserver", "internal/ai/capability"},
	// The gateway serves tools and dispatch; it neither runs battles nor calls models.
	"cmd/aigateway": {"internal/battle/worker", "internal/battle/api", "internal/app", "internal/ai/runner", "internal/ai/providers", "internal/ai/agent"},
	// The engine runs battles; model execution and the tool server live elsewhere.
	"cmd/engine": {"internal/app", "internal/battle/api", "internal/ai/mcpserver", "internal/ai/capability", "internal/ai/runner", "internal/ai/providers", "internal/ai/agent"},
	// The API serves HTTP; it neither runs battles nor calls models.
	"cmd/server": {"internal/battle/worker", "internal/ai/mcpserver", "internal/ai/capability", "internal/ai/runner", "internal/ai/providers", "internal/ai/agent"},
	// The persistence adapter implements the engine's contract without importing it.
	"internal/battle/repo": {"internal/battle/worker"},
	// Shared AI contracts import none of the subpackages built on them.
	"internal/ai": {"internal/ai/..."},
	// Loading configuration must not link database code.
	"internal/config": {"internal/postgres"},
	// The simulation domain stays free of AI, persistence, and HTTP code.
	"internal/game": {"internal/ai/...", "internal/postgres", "internal/httpapi"},
	// Domain services own the rules and depend on repository interfaces, not on the
	// adapters around them.
	"internal/battle/service":  {"internal/battle/repo", "internal/battle/api", "internal/battle/worker", "internal/postgres", "internal/httpapi"},
	"internal/faction/service": {"internal/faction/repo", "internal/faction/api", "internal/postgres", "internal/httpapi"},
	// HTTP handlers reach storage only through their service.
	"internal/battle/api":  {"internal/battle/repo", "internal/postgres"},
	"internal/faction/api": {"internal/faction/repo", "internal/postgres"},
	// The decision pipeline is pure: storage and transport stay with its callers.
	"internal/ai/decision":  {"internal/postgres", "internal/httpapi"},
	"internal/ai/briefing":  {"internal/postgres", "internal/httpapi"},
	"internal/ai/agentview": {"internal/postgres", "internal/httpapi"},
	// Generation's domain types serve both the API and the AI gateway; HTTP lives in
	// generation/api and storage in generation/repo.
	"internal/generation": {"internal/httpapi", "internal/apierror", "internal/postgres", "internal/generation/api", "internal/generation/repo"},
	// Observability packages are leaves, so any package can log, count, trace, or read the
	// request ID without an import cycle.
	"internal/observability/logging":   {"internal/..."},
	"internal/observability/metrics":   {"internal/..."},
	"internal/observability/tracing":   {"internal/..."},
	"internal/observability/requestid": {"internal/..."},
}

func TestForbiddenDependencies(t *testing.T) {
	deps := listDependencies(t)
	for pkg, rules := range forbidden {
		linked, ok := deps[pkg]
		if !ok {
			t.Errorf("%s: package not found; update the rule", pkg)
			continue
		}
		for _, dep := range linked {
			for _, rule := range rules {
				if matches(dep, rule) {
					t.Errorf("%s must not depend on %s (rule %q)", pkg, dep, rule)
				}
			}
		}
	}
}

// A rule naming a package that no longer exists would pass silently, for example after
// a rename, so every forbidden target must match at least one real package.
func TestForbiddenRulesNameExistingPackages(t *testing.T) {
	deps := listDependencies(t)
	for pkg, rules := range forbidden {
		for _, rule := range rules {
			found := false
			for candidate := range deps {
				if matches(candidate, rule) {
					found = true
					break
				}
			}
			if !found {
				t.Errorf("%s: rule %q matches no package; update it", pkg, rule)
			}
		}
	}
}

func TestComponentMapIsCurrent(t *testing.T) {
	want := componentMap(listDependencies(t))
	document, err := os.ReadFile(mapPath)
	if err != nil {
		t.Fatal(err)
	}
	start, end := bytes.Index(document, []byte(mapStart)), bytes.Index(document, []byte(mapEnd))
	if start < 0 || end < start {
		t.Fatalf("%s lacks the component map markers", mapPath)
	}
	current := string(document[start+len(mapStart) : end])
	if current == want {
		return
	}
	if !*update {
		t.Fatalf("the component map in %s is stale; run: go test ./test/boundaries -run TestComponentMapIsCurrent -update", mapPath)
	}
	rewritten := append(append(append([]byte{}, document[:start+len(mapStart)]...), want...), document[end:]...)
	if err := os.WriteFile(mapPath, rewritten, 0o644); err != nil {
		t.Fatal(err)
	}
}

func matches(dep, rule string) bool {
	if prefix, ok := strings.CutSuffix(rule, "/..."); ok {
		return strings.HasPrefix(dep, prefix+"/")
	}
	return dep == rule
}

// listDependencies returns each package's transitive internal dependencies, as paths
// relative to the module root. Test-only imports are excluded.
func listDependencies(t *testing.T) map[string][]string {
	t.Helper()
	trackSources(t)
	command := exec.Command("go", "list", "-json=ImportPath,Deps,Module", "./cmd/...", "./internal/...")
	command.Dir = moduleRoot
	output, err := command.Output()
	if err != nil {
		t.Fatalf("go list: %v", err)
	}
	result := map[string][]string{}
	decoder := json.NewDecoder(bytes.NewReader(output))
	for decoder.More() {
		var pkg struct {
			ImportPath string
			Deps       []string
			Module     struct{ Path string }
		}
		if err := decoder.Decode(&pkg); err != nil {
			t.Fatal(err)
		}
		prefix := pkg.Module.Path + "/"
		var internal []string
		for _, dep := range pkg.Deps {
			if relative, ok := strings.CutPrefix(dep, prefix); ok && strings.HasPrefix(relative, "internal/") {
				internal = append(internal, relative)
			}
		}
		result[strings.TrimPrefix(pkg.ImportPath, prefix)] = internal
	}
	return result
}

// go test caches a result against the files the test itself opens, and go list reads
// sources in a subprocess. Visiting every source makes any import change invalidate
// the cached result.
func trackSources(t *testing.T) {
	t.Helper()
	for _, root := range []string{"go.mod", "cmd", "internal"} {
		err := filepath.WalkDir(filepath.Join(moduleRoot, root), func(path string, entry os.DirEntry, err error) error {
			if err != nil || entry.IsDir() || !strings.HasSuffix(path, ".go") {
				return err
			}
			_, err = os.ReadFile(path)
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}

func componentMap(deps map[string][]string) string {
	linkedBy := map[string]map[string]bool{}
	for _, binary := range binaries {
		for _, dep := range deps[binary.dir] {
			if linkedBy[dep] == nil {
				linkedBy[dep] = map[string]bool{}
			}
			linkedBy[dep][binary.dir] = true
		}
	}
	packages := make([]string, 0, len(linkedBy))
	for pkg := range linkedBy {
		packages = append(packages, pkg)
	}
	sort.Strings(packages)
	var out strings.Builder
	out.WriteString("\n| Package |")
	for _, binary := range binaries {
		fmt.Fprintf(&out, " %s |", binary.name)
	}
	out.WriteString("\n| --- |" + strings.Repeat(" :-: |", len(binaries)) + "\n")
	for _, pkg := range packages {
		fmt.Fprintf(&out, "| [`%s`](../../backend/%s) |", strings.TrimPrefix(pkg, "internal/"), filepath.ToSlash(pkg))
		for _, binary := range binaries {
			mark := ""
			if linkedBy[pkg][binary.dir] {
				mark = "✓"
			}
			fmt.Fprintf(&out, " %s |", mark)
		}
		out.WriteString("\n")
	}
	return out.String()
}
